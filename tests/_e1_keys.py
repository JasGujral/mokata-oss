"""0.0.28 E1 (REDACT-MANGLED-KEY) — key fixtures built at RUN time from character codes.

This repo's own secret-guard hook scans every write, so a marker spelled out in a test file would
block the write of the test itself — and since 0.0.28 E1 even a marker split across string
literals is caught (that is the point of the lane). Every marker word here is assembled from
`chr()` codes, so no spelling of this file can glue back into a marker.

The key BODIES are synthesised DER with the real structure of each key type (PKCS#1 RSA at four
sizes, SEC1 EC on three curves, PKCS#8 RSA/EC/Ed25519, encrypted PKCS#8, OpenSSH), filled with
seeded random bytes: the unmarked-body backstop judges a key by its STRUCTURE, never by a fixed
string, so a structurally-true body is the honest fixture. `real_keys()` adds keys generated by
`openssl` when it is on PATH (a row that needs it records not-run otherwise).

Copyright 2026 MoStack. Licensed under the Apache License, Version 2.0.
"""

from __future__ import annotations

import base64
import random
import shutil
import subprocess
import tempfile
import os


def w(*codes: int) -> str:
    return "".join(chr(c) for c in codes)


BEGIN = w(66, 69, 71, 73, 78)
END = w(69, 78, 68)
PRIVATE = w(80, 82, 73, 86, 65, 84, 69)
KEY = w(75, 69, 89)
BLOCK = w(66, 76, 79, 67, 75)
RSA = w(82, 83, 65)
OPENSSH = w(79, 80, 69, 78, 83, 83, 72)
D5 = chr(45) * 5
SP = chr(32)

#: every type-word spelling a strict marker uses (the label between the keyword and PRIVATE)
TYPE_LABELS = ("", RSA, w(69, 67), w(68, 83, 65), OPENSSH, w(69, 78, 67, 82, 89, 80, 84, 69, 68),
               w(80, 71, 80), w(83, 83, 72, 50) + SP + w(69, 78, 67, 82, 89, 80, 84, 69, 68))


def marker(word: str, label: str = RSA, *, lead: str = D5, trail: str = D5, sep: str = SP,
           block: bool = False) -> str:
    """One marker: `lead` WORD [label] PRIVATE KEY [BLOCK] `trail`."""
    parts = [word] + ([label] if label else []) + [PRIVATE, KEY] + ([BLOCK] if block else [])
    return lead + sep.join(parts) + trail


def pair(label: str = RSA, **kw) -> tuple:
    return marker(BEGIN, label, **kw), marker(END, label, **kw)


# ------------------------------------------------------------------------------- DER bodies

def _len(n: int) -> bytes:
    if n < 0x80:
        return bytes([n])
    b = n.to_bytes((n.bit_length() + 7) // 8, "big")
    return bytes([0x80 | len(b)]) + b


def tlv(tag: int, body: bytes) -> bytes:
    return bytes([tag]) + _len(len(body)) + body


def seq(*parts: bytes) -> bytes:
    return tlv(0x30, b"".join(parts))


def integer(v: bytes) -> bytes:
    if v and v[0] & 0x80:
        v = b"\x00" + v
    return tlv(0x02, v or b"\x00")


def small(n: int) -> bytes:
    return tlv(0x02, bytes([n]))


def oid(hexs: str) -> bytes:
    return tlv(0x06, bytes.fromhex(hexs))


def octets(b: bytes) -> bytes:
    return tlv(0x04, b)


def bits(b: bytes) -> bytes:
    return tlv(0x03, b"\x00" + b)


OID_RSA = "2a864886f70d010101"
OID_EC = "2a8648ce3d0201"
CURVES = {"P-256": ("2a8648ce3d030107", 32), "P-384": ("2b81040022", 48), "P-521": ("2b81040023", 66)}
OID_ED25519 = "2b6570"
OID_PBES2 = "2a864886f70d01050d"


def _rnd(seed: str):
    return random.Random(seed)


def _bytes(r, n: int) -> bytes:
    return bytes(r.getrandbits(8) for _ in range(n))


def rsa_pkcs1(bits_: int, seed: str = "rsa") -> bytes:
    r = _rnd(f"{seed}-{bits_}")
    n = bits_ // 8
    return seq(small(0), integer(_bytes(r, n)), integer(b"\x01\x00\x01"), integer(_bytes(r, n)),
               *(integer(_bytes(r, n // 2)) for _ in range(5)))


def rsa_pkcs8(bits_: int) -> bytes:
    return seq(small(0), seq(oid(OID_RSA), b"\x05\x00"), octets(rsa_pkcs1(bits_, "p8")))


def ec_sec1(curve: str) -> bytes:
    o, n = CURVES[curve]
    r = _rnd(curve)
    return seq(small(1), octets(_bytes(r, n)), tlv(0xA0, oid(o)), tlv(0xA1, bits(b"\x04" + _bytes(r, 2 * n))))


def ec_pkcs8(curve: str) -> bytes:
    o, _n = CURVES[curve]
    return seq(small(0), seq(oid(OID_EC), oid(o)), octets(ec_sec1(curve)))


def ed25519_pkcs8() -> bytes:
    return seq(small(0), seq(oid(OID_ED25519)), octets(octets(_bytes(_rnd("ed"), 32))))


def encrypted_pkcs8() -> bytes:
    r = _rnd("enc")
    return seq(seq(oid(OID_PBES2), seq(seq(oid("2a864886f70d01050c"), seq(octets(_bytes(r, 8)),
                                                                        small(8))))),
               octets(_bytes(r, 1232)))


def openssh_key() -> bytes:
    return b"openssh-key-v1\x00" + _bytes(_rnd("ossh"), 380)


#: every unmarked-body key shape of the E1.Unmarked row
KEY_BODIES = {
    **{f"rsa{b}": rsa_pkcs1(b) for b in (1024, 2048, 3072, 4096)},
    **{f"rsa{b}-pkcs8": rsa_pkcs8(b) for b in (2048,)},
    **{f"ec-{c}": ec_sec1(c) for c in CURVES},
    **{f"ec-{c}-pkcs8": ec_pkcs8(c) for c in CURVES},
    "ed25519": ed25519_pkcs8(),
    "encrypted-pkcs8": encrypted_pkcs8(),
    "openssh": openssh_key(),
}


def certificate() -> bytes:
    r = _rnd("cert")
    tbs = seq(tlv(0xA0, small(2)), integer(_bytes(r, 16)), seq(oid("2a864886f70d01010b")),
              _bytes(r, 400))
    return seq(tbs, seq(oid("2a864886f70d01010b")), bits(_bytes(r, 256)))


def spki() -> bytes:
    return seq(seq(oid(OID_RSA), b"\x05\x00"), bits(seq(integer(_bytes(_rnd("pk"), 256)),
                                                       integer(b"\x01\x00\x01"))))


def rsa_public() -> bytes:
    return seq(integer(_bytes(_rnd("pub"), 256)), integer(b"\x01\x00\x01"))


def b64_lines(der: bytes, width: int) -> list:
    t = base64.b64encode(der).decode("ascii")
    return [t[i:i + width] for i in range(0, len(t), width)]


def random_body(width: int, lines: int = 20, seed: str = "body") -> list:
    """Base64-alphabet lines that decode to NOTHING structured: a marked key's body."""
    alpha = w(*range(65, 91)) + w(*range(97, 123)) + w(*range(48, 58)) + "+/"
    r = _rnd(f"{seed}-{width}-{lines}")
    return ["".join(r.choice(alpha) for _ in range(width)) for _ in range(lines)]


def real_keys() -> dict:
    """{name: PEM text} generated by `openssl` now, or {} when it is not on PATH."""
    exe = shutil.which("openssl")
    if not exe:
        return {}
    out = {}
    d = tempfile.mkdtemp(prefix="mk-e1-openssl-")
    try:
        specs = {"rsa2048": ["-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:2048"],
                 "ec-p256": ["-algorithm", "EC", "-pkeyopt", "ec_paramgen_curve:P-256"],
                 "ed25519": ["-algorithm", "ED25519"]}
        for name, args in specs.items():
            p = os.path.join(d, name)
            r = subprocess.run([exe, "genpkey", *args, "-out", p], capture_output=True,
                               stdin=subprocess.DEVNULL)
            if r.returncode == 0:
                with open(p, encoding="ascii") as fh:
                    out[name] = fh.read()
    finally:
        shutil.rmtree(d, ignore_errors=True)
    return out


def _pem_der(path: str) -> bytes:
    with open(path, encoding="ascii") as fh:
        body = "".join(ln for ln in fh.read().splitlines() if ln and not ln.startswith("-"))
    return base64.b64decode(body)


def four_real_keys() -> dict:
    """{name: (der, real?)} for the round-3 matrix: RSA PKCS#1, RSA PKCS#8, EC SEC1 and an
    OpenSSH Ed25519 key, generated by `openssl` / `ssh-keygen` now. A key a tool cannot make here
    falls back to the synthesised DER of the same type (real? = False, recorded by the test)."""
    fallback = {"rsa-pkcs1": KEY_BODIES["rsa2048"], "rsa-pkcs8": KEY_BODIES["rsa2048-pkcs8"],
                "ec-sec1": KEY_BODIES["ec-P-256"], "openssh-ed25519": KEY_BODIES["openssh"]}
    ossl, sshk = shutil.which("openssl"), shutil.which("ssh-keygen")
    cmds = {
        "rsa-pkcs1": [[ossl, "genrsa", "-traditional", "-out", "{p}", "2048"],
                      [ossl, "genrsa", "-out", "{p}", "2048"]] if ossl else [],
        "rsa-pkcs8": [[ossl, "genpkey", "-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:2048",
                       "-out", "{p}"]] if ossl else [],
        "ec-sec1": [[ossl, "ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", "{p}"]]
        if ossl else [],
        "openssh-ed25519": [[sshk, "-q", "-t", "ed25519", "-N", "", "-C", "", "-f", "{p}"]]
        if sshk else [],
    }
    want = {"rsa-pkcs1": RSA, "rsa-pkcs8": "", "ec-sec1": w(69, 67), "openssh-ed25519": OPENSSH}
    out = {}
    d = tempfile.mkdtemp(prefix="mk-e1-real4-")
    try:
        for name, tries in cmds.items():
            got = None
            for i, cmd in enumerate(tries):
                p = os.path.join(d, f"{name}-{i}")
                r = subprocess.run([a.format(p=p) for a in cmd], capture_output=True,
                                   stdin=subprocess.DEVNULL)
                if r.returncode != 0 or not os.path.exists(p):
                    continue
                with open(p, encoding="ascii") as fh:
                    head = fh.readline()
                words = head.strip("-\n").split()
                if (want[name] and want[name] in words) or (not want[name] and len(words) == 3):
                    got = _pem_der(p)
                    break
            out[name] = (got, True) if got else (fallback[name], False)
    finally:
        shutil.rmtree(d, ignore_errors=True)
    return out
